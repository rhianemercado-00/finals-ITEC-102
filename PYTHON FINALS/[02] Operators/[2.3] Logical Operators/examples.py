# Logical Operators - Examples

#------- Easy Examples -------

# Example 1: and
print("Example 1")
print(True and True)     # True
print(True and False)    # False

# Example 2: or
print("\nExample 2")
print(True or False)     # True
print(False or False)    # False

# Example 3: not
print("\nExample 3")
print(not True)          # False
is_logged_in = False
print(not is_logged_in)  # True

#------- Intermediate Examples -------

# Example 4: and with comparisons
print("\nExample 4")
age = 20
print(age >= 18 and age <= 25)   # True

# Example 5: or with comparisons
print("\nExample 5")
temperature = 35
print(temperature < 0 or temperature > 30)   # True

# Example 6: Passing range
print("\nExample 6")
score = 85
print(score >= 75 and score <= 100)   # True

