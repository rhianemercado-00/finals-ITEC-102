# Intermediate 6 — sorted() function
# sorted() is a built-in function. It returns a new sorted list and leaves the original list unchanged.
prices = [250, 100, 400, 150]
new_prices = sorted(prices)
print("Original:", prices)
print("Sorted copy:", new_prices)

# Output:
# Original: [250, 100, 400, 150]
# Sorted copy: [100, 150, 250, 400]